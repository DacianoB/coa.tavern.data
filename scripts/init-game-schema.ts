import { existsSync } from "node:fs";
import { Pool } from "pg";

if (existsSync(".env")) {
  process.loadEnvFile(".env");
}

const AOWOW_SCHEMA_URL =
  "https://raw.githubusercontent.com/azerothcore/aowow/master/setup/db_structure.sql";

const connectionString = process.env.GAME_DATABASE_URL || process.env.DATABASE_URL;
const targetSchema = process.env.GAME_DATABASE_SCHEMA || "game";

function quoteIdent(identifier: string) {
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(identifier)) {
    throw new Error(`Unsafe SQL identifier: ${identifier}`);
  }

  return `"${identifier}"`;
}

function makeIdentifier(...parts: string[]) {
  const normalized = parts
    .join("_")
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_+|_+$/g, "");

  return normalized.slice(0, 60) || "idx";
}

function splitColumns(body: string) {
  const lines: string[] = [];
  let current = "";
  let depth = 0;
  let inString = false;

  for (const char of body) {
    if (char === "'" && !current.endsWith("\\")) {
      inString = !inString;
    }

    if (!inString) {
      if (char === "(") depth += 1;
      if (char === ")") depth -= 1;
    }

    if (char === "," && depth === 0 && !inString) {
      lines.push(current.trim());
      current = "";
    } else {
      current += char;
    }
  }

  if (current.trim()) {
    lines.push(current.trim());
  }

  return lines;
}

function convertDefault(value: string) {
  return value
    .replace(/DEFAULT b'([01])'/gi, "DEFAULT $1")
    .replace(/DEFAULT _utf8mb4'([^']*)'/gi, "DEFAULT '$1'")
    .replace(/DEFAULT current_timestamp\(\)/gi, "DEFAULT CURRENT_TIMESTAMP")
    .replace(/DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP/gi, "DEFAULT CURRENT_TIMESTAMP");
}

function convertColumn(line: string) {
  const match = line.match(/^`([^`]+)`\s+([\s\S]+)$/);

  if (!match) {
    return null;
  }

  const [, name, rawRest] = match;
  let rest = rawRest
    .replace(/\s+COMMENT\s+'(?:\\'|[^'])*'/gi, "")
    .replace(/\s+COLLATE\s+\w+/gi, "")
    .replace(/\s+CHARACTER SET\s+\w+/gi, "")
    .replace(/\s+UNSIGNED/gi, "")
    .replace(/\s+SIGNED/gi, "")
    .replace(/\s+ZEROFILL/gi, "")
    .replace(/\s+AUTO_INCREMENT/gi, " GENERATED BY DEFAULT AS IDENTITY")
    .replace(/\s+ON UPDATE CURRENT_TIMESTAMP/gi, "")
    .replace(/\btinyint\s*\(\s*\d+\s*\)/gi, "smallint")
    .replace(/\bsmallint\s*\(\s*\d+\s*\)/gi, "smallint")
    .replace(/\bmediumint\s*\(\s*\d+\s*\)/gi, "integer")
    .replace(/\bint\s*\(\s*\d+\s*\)/gi, "integer")
    .replace(/\bbigint\s*\(\s*\d+\s*\)/gi, "bigint")
    .replace(/\btinyint\b/gi, "smallint")
    .replace(/\bmediumint\b/gi, "integer")
    .replace(/\bint\b/gi, "integer")
    .replace(/\bdouble\s*\((\d+)\s*,\s*(\d+)\)/gi, "numeric($1,$2)")
    .replace(/\bfloat\s*\((\d+)\s*,\s*(\d+)\)/gi, "numeric($1,$2)")
    .replace(/\bdouble\b/gi, "double precision")
    .replace(/\bfloat\b/gi, "real")
    .replace(/\bdatetime\b/gi, "timestamp")
    .replace(/\bmediumtext\b/gi, "text")
    .replace(/\blongtext\b/gi, "text")
    .replace(/\btinytext\b/gi, "text")
    .replace(/\bvarbinary\((\d+)\)/gi, "bytea")
    .replace(/\bblob\b/gi, "bytea")
    .replace(/\benum\([^)]+\)/gi, "text")
    .replace(/`/g, "\"");

  rest = convertDefault(rest);

  return `${quoteIdent(name)} ${rest}`;
}

function convertConstraint(line: string) {
  const primary = line.match(/^PRIMARY KEY\s+\((.+)\)$/i);
  if (primary) {
    return `PRIMARY KEY (${primary[1].replace(/`([^`]+)`/g, (_, name) => quoteIdent(name))})`;
  }

  return null;
}

function convertIndex(tableName: string, line: string) {
  const match = line.match(/^(UNIQUE\s+)?(?:FULLTEXT\s+|SPATIAL\s+)?KEY\s+`([^`]+)`\s+\((.+)\)$/i);

  if (!match) {
    return null;
  }

  const [, unique, keyName, rawColumns] = match;
  const columns = rawColumns
    .split(",")
    .map((column) => column.trim().replace(/`([^`]+)`(?:\(\d+\))?/g, (_, name) => quoteIdent(name)))
    .join(", ");
  const indexName = quoteIdent(makeIdentifier(tableName, keyName, unique ? "uidx" : "idx"));

  return `CREATE ${unique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${indexName} ON ${quoteIdent(targetSchema)}.${quoteIdent(tableName)} (${columns});`;
}

function convertCreateTables(mysqlSql: string) {
  const blocks = Array.from(
    mysqlSql.matchAll(/CREATE TABLE `([^`]+)` \(([\s\S]*?)\)\s+ENGINE=/g),
  );

  return blocks.map((block) => {
    const [, tableName, body] = block;
    const parts = splitColumns(body);
    const converted = parts
      .map((line) => convertColumn(line) ?? convertConstraint(line))
      .filter((line): line is string => Boolean(line));
    const indexes = parts
      .map((line) => convertIndex(tableName, line))
      .filter((line): line is string => Boolean(line));

    return {
      tableName,
      sql: `CREATE TABLE IF NOT EXISTS ${quoteIdent(targetSchema)}.${quoteIdent(tableName)} (\n  ${converted.join(",\n  ")}\n);`,
      indexes,
    };
  });
}

