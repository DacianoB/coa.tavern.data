async function main() {
  if (!connectionString) {
    throw new Error("GAME_DATABASE_URL or DATABASE_URL must be set.");
  }

  const response = await fetch(AOWOW_SCHEMA_URL);
  if (!response.ok) {
    throw new Error(`Failed to fetch AoWoW schema: ${response.status}`);
  }

  const mysqlSql = await response.text();
  const statements = convertCreateTables(mysqlSql);
  const helpers = helperTableStatements();
  const pool = new Pool({ connectionString });
  const schema = quoteIdent(targetSchema);

  await pool.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`);

  for (const statement of [...statements, ...helpers]) {
    try {
      await pool.query(statement.sql);
      for (const indexSql of statement.indexes) {
        await pool.query(indexSql);
      }
    } catch (error) {
      console.error(`Failed while creating ${targetSchema}.${statement.tableName}`);
      console.error(statement.sql);
      throw error;
    }
  }

  await pool.end();
  console.log(
    `Created/verified ${statements.length} AoWoW-compatible tables and ${helpers.length} helper tables in schema ${targetSchema}.`,
  );
  console.log("This initializes schema only. Populate data from AoWoW/AzerothCore import outputs before production use.");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
